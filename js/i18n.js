var currentLang = 'es';
try {
  var saved = localStorage.getItem('ve-lang');
  if (saved && translations[saved]) currentLang = saved;
} catch (e) {}

/* t(key, vars): traducción para textos generados desde JS (alertas, etc.) */
function t(key, vars) {
  var str = (translations[currentLang] && translations[currentLang][key]) ||
            translations.es[key] || key;
  if (vars) {
    for (var v in vars) str = str.split('{' + v + '}').join(vars[v]);
  }
  return str;
}

var ATTR_MAP = {
  'data-i18n-placeholder': 'placeholder',
  'data-i18n-alt': 'alt',
  'data-i18n-aria': 'aria-label',
  'data-i18n-title': 'title',
  'data-i18n-content': 'content'
};

function applyTranslations(lang) {
  if (!translations[lang]) return;
  currentLang = lang;
  try { localStorage.setItem('ve-lang', lang); } catch (e) {}
  var dict = translations[lang];

  document.documentElement.setAttribute('lang', lang);

  var nodes = document.querySelectorAll('[data-i18n]');
  for (var i = 0; i < nodes.length; i++) {
    var key = nodes[i].getAttribute('data-i18n');
    if (dict[key] !== undefined) nodes[i].innerHTML = dict[key];
  }

  Object.keys(ATTR_MAP).forEach(function (dataAttr) {
    var els = document.querySelectorAll('[' + dataAttr + ']');
    for (var a = 0; a < els.length; a++) {
      var k = els[a].getAttribute(dataAttr);
      if (dict[k] !== undefined) els[a].setAttribute(ATTR_MAP[dataAttr], dict[k]);
    }
  });

  var wa = document.querySelectorAll('[data-i18n-wa]');
  for (var w = 0; w < wa.length; w++) {
    var wk = wa[w].getAttribute('data-i18n-wa');
    var base = wa[w].getAttribute('href').split('?')[0];
    wa[w].setAttribute('href', base + '?text=' + encodeURIComponent(dict[wk] || ''));
  }

  var buttons = document.querySelectorAll('.lang-btn');
  for (var j = 0; j < buttons.length; j++) {
    var on = buttons[j].getAttribute('data-lang') === lang;
    buttons[j].classList.toggle('active', on);
    buttons[j].setAttribute('aria-pressed', on ? 'true' : 'false');
  }

  document.dispatchEvent(new CustomEvent('languagechange', { detail: { lang: lang } }));
}

function setLanguage(lang) { applyTranslations(lang); }

var i18nBound = false;
function initI18n() {
  applyTranslations(currentLang);
  if (i18nBound) return;
  i18nBound = true;
  document.addEventListener('click', function (e) {
    var btn = e.target.closest('.lang-btn');
    if (!btn) return;
    e.preventDefault();
    var lang = btn.getAttribute('data-lang');
    if (lang) applyTranslations(lang);
  });
}

/* Los scripts van al final del body: el DOM ya existe, se aplica sin parpadeo */
if (document.body) initI18n();
document.addEventListener('DOMContentLoaded', initI18n);

window.t = t;
window.setLanguage = setLanguage;
window.applyTranslations = applyTranslations;
